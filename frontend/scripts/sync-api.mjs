// Generates src/api/types.gen.ts from the API's OpenAPI document (DESIGN.md 4.7).
// The API is FastAPI, which serves the document at /openapi.json by default.
// Usage: npm run sync:api            (uses VITE_API_URL from .env, else http://localhost:4000)
//        npm run sync:api -- <url>   (any URL or local file path to an OpenAPI document)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

function apiUrlFromEnv() {
  if (process.env.VITE_API_URL) return process.env.VITE_API_URL;
  if (existsSync(".env")) {
    const line = readFileSync(".env", "utf8").split(/\r?\n/).find((l) => l.startsWith("VITE_API_URL="));
    if (line) return line.slice("VITE_API_URL=".length).trim();
  }
  return "http://localhost:4000";
}

const source = process.argv[2] ?? `${apiUrlFromEnv().replace(/\/$/, "")}/openapi.json`;
const input = /^https?:/.test(source) ? new URL(source) : pathToFileURL(resolve(source));

try {
  const ast = await openapiTS(input);
  const header = `// Generated by \`npm run sync:api\` from ${source}. Do not edit by hand.\n\n`;
  writeFileSync("src/api/types.gen.ts", header + astToString(ast));
  console.log(`Wrote src/api/types.gen.ts from ${source}`);
} catch (e) {
  console.error(`Could not generate types from ${source}: ${e.message}`);
  console.error("Is the API running? Start control-tower-api, or pass a path to a saved openapi.json.");
  process.exit(1);
}
